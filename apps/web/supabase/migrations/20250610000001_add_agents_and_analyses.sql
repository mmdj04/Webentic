to public
using ((auth.uid() = user_id));

-- RLS Policies for agent_logs
create policy "Users can view logs of their agents"
on "public"."agent_logs"
as permissive
for select
to public
using ((EXISTS ( SELECT 1
   FROM agent_configs
  WHERE ((agent_configs.id = agent_logs.agent_id) AND (agent_configs.user_id = auth.uid())))));

create policy "Users can insert logs for their agents"
on "public"."agent_logs"
as permissive
for insert
to public
with check ((EXISTS ( SELECT 1
   FROM agent_configs
  WHERE ((agent_configs.id = agent_logs.agent_id) AND (agent_configs.user_id = auth.uid())))));

